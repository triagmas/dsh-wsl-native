// Build the published artifacts from the TypeScript sources.
// - dist/index.js   host plugin entry (bundled ESM, Harness peer left external)
// - dist/service.js public service entry used by tooling and tests
// - dist/worker.js  resident bridge worker injected into the target process
// - dist/cli.js     `dsh-wsl` command line entry
// - dist/client.js  DSH client module bundle (single file, size limited)
// - dist/types/**   generated declaration files from tsc
import { build } from 'esbuild';
import { execFile } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const run = promisify(execFile);
const root = fileURLToPath(new URL('../', import.meta.url));

/** Client bundle ceiling enforced by the DSH client module loader. */
export const CLIENT_BUNDLE_LIMIT = 262144;

const nodeOptions = {
  absWorkingDir: root,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  legalComments: 'none',
  logLevel: 'warning',
};

export async function buildWorker() {
  await build({
    ...nodeOptions,
    entryPoints: ['src/worker.ts'],
    outfile: 'dist/worker.js',
  });
}

export async function buildHost() {
  await build({
    ...nodeOptions,
    entryPoints: ['src/index.ts'],
    outfile: 'dist/index.js',
    external: ['@deepseek-ai/dsh-tools', '@deepseek-ai/cordis'],
  });
  await build({
    ...nodeOptions,
    entryPoints: ['src/service.ts'],
    outfile: 'dist/service.js',
    external: ['@deepseek-ai/dsh-tools', '@deepseek-ai/cordis'],
  });
  await build({
    ...nodeOptions,
    entryPoints: ['src/cli.ts'],
    outfile: 'dist/cli.js',
    banner: { js: '#!/usr/bin/env node' },
  });
  await fs.chmod(path.join(root, 'dist/cli.js'), 0o755);
}

export async function buildClient() {
  const client = await build({
    absWorkingDir: root,
    entryPoints: ['src/client.tsx'],
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: 'es2022',
    minify: true,
    write: false,
    jsx: 'automatic',
    loader: { '.css': 'text' },
    external: ['react', 'react/jsx-runtime', '@deepseek-ai/dsh-client-ui-primitives'],
    legalComments: 'none',
    logLevel: 'warning',
  });
  const wrapped = `window.__ModuleLoader__.load({id:"dsh-wsl-native",factory:(require)=>{const module={exports:{}};const exports=module.exports;\n${client.outputFiles[0].text}\nreturn module.exports;}});\n`;
  if (Buffer.byteLength(wrapped) > CLIENT_BUNDLE_LIMIT) {
    throw new Error(`client bundle exceeds DSH size limit: ${Buffer.byteLength(wrapped)} bytes`);
  }
  await fs.writeFile(path.join(root, 'dist/client.js'), wrapped);
  return Buffer.byteLength(wrapped);
}

async function main() {
  await fs.mkdir(path.join(root, 'dist'), { recursive: true });
  await buildHost();
  await buildWorker();
  const clientBytes = await buildClient();
  // Declarations are generated by tsc so the published types stay authoritative.
  await run(process.execPath, [path.join(root, 'node_modules/typescript/bin/tsc'), '-p', 'tsconfig.build.json'], {
    cwd: root,
  });
  console.log(`Client bundle: ${clientBytes} / ${CLIENT_BUNDLE_LIMIT} bytes.`);
  console.log('Built dsh-wsl-native host, worker, cli, client and declarations.');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await main();
}
